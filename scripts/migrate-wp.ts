/**
 * AFI-L'UE WordPress to Next.js / Supabase Extraction & Migration Script
 * Source: https://afi-ue.sn/wp-json/wp/v2/
 */

import * as fs from "node:fs";
import * as path from "node:path";

interface WpCategory {
  id: number;
  name: string;
  slug: string;
  count: number;
  description: string;
}

interface WpPost {
  id: number;
  date: string;
  slug: string;
  status: string;
  link: string;
  title: { rendered: string };
  content: { rendered: string };
  excerpt: { rendered: string };
  categories: number[];
  tags: number[];
}

export function cleanDiviShortcodes(rawContent: string): string {
  if (!rawContent) return "";
  // Strip all [et_pb_*] opening, closing, and self-closing tags
  let cleaned = rawContent.replace(/\[\/?et_pb_[^\]]*\]/gi, "");
  // Strip empty paragraphs generated by WordPress
  cleaned = cleaned.replace(/<p>\s*<\/p>/gi, "");
  // Trim excessive whitespace
  cleaned = cleaned.trim();
  return cleaned;
}

export function decodeHtmlEntities(str: string): string {
  return str
    .replace(/&#8217;/g, "'")
    .replace(/&#8216;/g, "'")
    .replace(/&#8220;/g, '"')
    .replace(/&#8221;/g, '"')
    .replace(/&#8211;/g, "–")
    .replace(/&#8212;/g, "—")
    .replace(/&amp;/g, "&")
    .replace(/&eacute;/g, "é")
    .replace(/&egrave;/g, "è")
    .replace(/&agrave;/g, "à")
    .replace(/&ccedil;/g, "ç")
    .replace(/&ecirc;/g, "ê")
    .replace(/&icirc;/g, "î")
    .replace(/&ocirc;/g, "ô")
    .replace(/&ucirc;/g, "û");
}

async function fetchFromWp<T>(endpoint: string): Promise<T[]> {
  const url = `https://afi-ue.sn/wp-json/wp/v2/${endpoint}`;
  try {
    const res = await fetch(url, { headers: { "User-Agent": "AFI-Migration/1.0" } });
    if (!res.ok) {
      console.warn(`Failed to fetch ${url}: HTTP ${res.status}`);
      return [];
    }
    return (await res.json()) as T[];
  } catch (err) {
    console.warn(`Fetch error for ${url}:`, err);
    return [];
  }
}

async function runMigration() {
  console.log("🚀 Lancement de l'inventaire et de l'extraction WordPress AFI-L'UE...");

  const categories = await fetchFromWp<WpCategory>("categories?per_page=50");
  console.log(`✅ Catégories récupérées : ${categories.length}`);

  const posts = await fetchFromWp<WpPost>("posts?per_page=20");
  console.log(`✅ Articles récents récupérés : ${posts.length}`);

  const cleanedArticles = posts.map((post) => ({
    legacy_wp_id: post.id,
    legacy_url: post.link,
    title: decodeHtmlEntities(post.title.rendered),
    slug: post.slug,
    published_at: post.date,
    excerpt: decodeHtmlEntities(cleanDiviShortcodes(post.excerpt.rendered)),
    cleaned_content: cleanDiviShortcodes(post.content.rendered),
  }));

  const redirects = cleanedArticles.map((a) => ({
    from: `/${a.slug}/`,
    to: `/actualites/${a.slug}`,
    status: 301,
  }));

  const report = {
    timestamp: new Date().toISOString(),
    source_url: "https://afi-ue.sn/",
    summary: {
      categories_found: categories.length,
      articles_extracted: cleanedArticles.length,
      redirects_generated: redirects.length,
    },
    categories: categories.map((c) => ({ id: c.id, name: c.name, slug: c.slug, count: c.count })),
    sample_cleaned_articles: cleanedArticles.slice(0, 5),
    redirect_sample: redirects.slice(0, 10),
  };

  const outputDir = path.join(process.cwd(), "docs");
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const outputPath = path.join(outputDir, "migration-report.json");
  fs.writeFileSync(outputPath, JSON.stringify(report, null, 2), "utf-8");
  console.log(`📄 Rapport de migration sauvegardé dans : ${outputPath}`);
}

if (process.argv[1]?.includes("migrate-wp")) {
  runMigration().catch(console.error);
}

